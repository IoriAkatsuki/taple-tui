#!/usr/bin/env python3
"""Generate native Metal MSL from checked-in SPIR-V. Requires spirv-cross on PATH.

This is a development tool, not a runtime dependency. Metal loads the resulting
MSL directly; there is no Vulkan loader, MoltenVK, or SPIRV-Cross in the player.
"""
import hashlib
import pathlib
import shutil
import subprocess
import sys

path = pathlib.Path(__file__).with_name("walkman.comp.spv")
cross = shutil.which("spirv-cross")
if not cross:
    sys.exit("spirv-cross is required to generate native Metal MSL")
msl = subprocess.check_output([cross, str(path), "--msl", "--msl-version", "20000"], text=True)
# Explicit fast intrinsics bypass fastMathEnabled=NO on Intel Metal drivers.
msl = msl.replace("fast::normalize(", "precise::normalize(")
msl = "\n".join(line.rstrip() for line in msl.splitlines()).rstrip() + "\n"
header = "// Code generated by compile_metal.py (SPIRV-Cross); DO NOT EDIT.\n"
header += "// SPIR-V SHA256: " + hashlib.sha256(path.read_bytes()).hexdigest() + "\n"
path.with_name("walkman.metal").write_text(header + msl, encoding="utf-8", newline="\n")
