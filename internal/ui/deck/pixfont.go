func PixGlyph(r rune) [7]uint8 { return pixGlyphs[unicode.ToUpper(r)] }

// PixSample samples a surface label; gap is measured in face units.
func PixSample(text string, u, v, pixelW, pixelH, gap float64) bool {
	if u < 0 || v < 0 || pixelW <= 0 || pixelH <= 0 || gap < 0 || math.IsNaN(u+v) {
		return false
	}
	row := int(math.Floor(v / pixelH))
	if row >= 7 {
		return false
	}
	stride := 5*pixelW + gap
	idx := int(math.Floor(u / stride))
	col := int(math.Floor((u - float64(idx)*stride) / pixelW))
	if col >= 5 {
		return false
	}
	for _, r := range text {
		if idx == 0 {
			return PixGlyph(r)[row]&(1<<(4-col)) != 0
		}
		idx--
	}
	return false
}
